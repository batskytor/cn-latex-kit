LATEXMKRC = r'''# Generated by cn-latex-kit
# Force XeLaTeX: fontspec/xeCJK + CJK fonts cannot be built by pdfLaTeX.
$pdf_mode = 1;
$pdflatex = 'xelatex %O %S';
'''


def _equivenum_code(spec: FormatSpec) -> str:
    if spec.equation_number_by_section:
        return (r"\numberwithin{equation}{section}"
                "\n" + r"\renewcommand{\theequation}{\arabic{section}-\arabic{equation}}")
    return r"\renewcommand{\theequation}{\arabic{equation}}"


def _caption_pos(above: bool) -> str:
    return "top" if above else "bottom"


class LatexGenerator:
    """Render LaTeX files from a :class:`FormatSpec`."""

    def __init__(self, spec: FormatSpec, cls_name: str = "journaltemplate") -> None:
        self.spec = spec
        self.cls_name = cls_name

    def render_cls(self) -> str:
        s = self.spec
        journal = s.journal_name or "学 报 名 称"
        journal_en = "Journal Template" if not s.journal_name else s.journal_name
        repl = {
            "\\clsname": self.cls_name,
            "\\sourcefile": s.source_docx or "unknown",
            "\\paperopt": s.page.paper_option,
            "\\bodyzihao": zihao(s.sizes.body),
            "\\latinfont": s.fonts.latin,
            "\\bodyfont": s.fonts.cjk_body,
            "\\headingfont": s.fonts.cjk_heading,
            "\\abstractfont": s.fonts.cjk_abstract,
            "\\monofont": s.fonts.cjk_mono,
            "\\topmm": f"{s.page.top_mm}mm",
            "\\bottommm": f"{s.page.bottom_mm}mm",
            "\\leftmm": f"{s.page.left_mm}mm",
            "\\rightmm": f"{s.page.right_mm}mm",
            "\\colsep": f"{s.page.columnsep_mm}mm",
            "\\bodylinespread": f"{s.body_line_spacing}",
            "\\bodyindent": f"{s.body_indent_em:g}",
            "\\zihaocaption": zihao(s.sizes.caption),
            "\\journalname": journal,
            "\\journalnameen": journal_en,
            "\\zihaoheadingone": zihao(s.sizes.heading1),
            "\\headingonelinespread": f"{s.heading1_line_spacing}",
            "\\zihaoheadingtwo": zihao(s.sizes.heading2),
            "\\figcappos": _caption_pos(s.caption_figure_below),
            "\\tabcappos": _caption_pos(s.caption_table_above),
            "\\equivenum": _equivenum_code(s),
            "\\zihaoref": zihao(s.sizes.reference),
            "\\reflinespread": f"{s.reference_line_spacing}",
            "\\zihaotitle": zihao(s.sizes.title),
            "\\zihaoauthor": zihao(s.sizes.author),
            "\\zihaoaffil": zihao(s.sizes.affiliation),
            "\\zihaoabstract": zihao(s.sizes.abstract),
            "\\zihaoentitle": zihao(s.sizes.en_title),
            "\\zihaoauthorinfo": zihao(s.sizes.author_info),
        }
        out = CLS_TEMPLATE
        # Replace longer placeholders first: \zihaoauthor is a prefix of
        # \zihaoauthorinfo, so naive order would leave a stray "info".
        for key in sorted(repl, key=len, reverse=True):
            out = out.replace(key, repl[key])
        return out

    def render_main(self) -> str:
        s = self.spec
        repl = {
            "\\clsname": self.cls_name,
            "\\cnTITLE": s.journal_name or "论文中文题目",
            "\\cnAUTHOR": "作者一$^{1}$，作者二$^{2}$",
            "\\cnAFFIL": "(1. 单位一，城市 邮编；2. 单位二，城市 邮编)",
            "\\cnABSTRACT": "摘要内容：按报道性摘要撰写，给出目的、过程、结果和结论，字数一般 250--300 汉字。",
            "\\cnKEYWORDS": "关键词一；关键词二；关键词三",
            "\\enTITLE": "English Title of the Paper",
            "\\enAUTHOR": "AUTHOR One$^{1}$, AUTHOR Two$^{2}$",
            "\\enAFFIL": "(1. Affiliation One, City, Country; 2. Affiliation Two, City, Country)",
            "\\enABSTRACT": "Contents of the abstract in English.",
            "\\enKEYWORDS": "keyword one; keyword two; keyword three",
            "\\journalNAME": s.journal_name or "学 报 名 称",
            "\\journalNAMEEN": "Journal Template",
        }
        out = MAIN_TEX_TEMPLATE
        for key in sorted(repl, key=len, reverse=True):
            out = out.replace(key, repl[key])
        return out

    def render_latexmkrc(self) -> str:
        return LATEXMKRC

    def write_all(self, out_dir: str | Path) -> list[Path]:
        """Write all three files into *out_dir* and return their paths."""
        out = Path(out_dir)
        out.mkdir(parents=True, exist_ok=True)
        cls_path = out / f"{self.cls_name}.cls"
        tex_path = out / "main.tex"
        rc_path = out / ".latexmkrc"
        cls_path.write_text(self.render_cls(), encoding="utf-8")
        tex_path.write_text(self.render_main(), encoding="utf-8")
        rc_path.write_text(self.render_latexmkrc(), encoding="utf-8")
        return [cls_path, tex_path, rc_path]
