"""Generate a compilable LaTeX template from a :class:`FormatSpec`.

The generator emits three files:

* ``<name>.cls``  - a class implementing every extracted rule;
* ``main.tex``    - a filled example document using the class;
* ``.latexmkrc``  - forces XeLaTeX so the user's ``latexmk -pdf`` works.

All values come from the spec, so feeding a different Word template yields a
different, ready-to-use LaTeX class without editing LaTeX by hand.
"""

